export const MESSAGES = { en, 'pt-BR': ptBR, es };
let language = 'en';

export function setLanguage(value) {
  language = Object.hasOwn(MESSAGES, value) ? value : 'en';
  document.documentElement.lang = language;
}

export function t(key, params) {
  const table = MESSAGES[language];
  let text = Object.hasOwn(table, key) ? table[key] : (en[key] ?? key);
  if (params)
    text = text.replace(/\{(\w+)\}/g, (match, name) =>
      Object.hasOwn(params, name) ? String(params[name]) : match,
    );
  return text;
}

export function translate(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-html]'))
    if (Object.hasOwn(en, el.dataset.i18nHtml)) el.innerHTML = t(el.dataset.i18nHtml);
  for (const el of root.querySelectorAll('[data-i18n-attr]'))
    for (const pair of el.dataset.i18nAttr.split(';')) {
      const [attr, key] = pair.split('=').map((part) => part.trim());
      if (attr && key) el.setAttribute(attr, t(key));
    }
  const title = document.querySelector('title[data-i18n-title]');
  if (title) document.title = t(title.dataset.i18nTitle);
}
